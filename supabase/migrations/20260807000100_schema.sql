-- ── 1. COURSES ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS courses (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  code        text unique,          -- e.g. 'code8', 'code10'
  created_at  timestamptz default now()
);

